def build_user_prompt(question: str, sources: Sequence[SourceEvidence]) -> str:
    """Serialize complete retrieved chunks without altering their metadata."""

    blocks = []
    for source in sources:
        blocks.append(
            f"[{source.source_id}]\n"
            f"Документ: {source.document}\n"
            f"Обозначение: {source.designation or 'не указано'}\n"
            f"Страница PDF: {source.page}\n"
            f"Chunk ID: {source.chunk_id}\n"
            f"Текст:\n{source.text}"
        )
    context = "\n\n---\n\n".join(blocks)
    return (
        "Ниже приведены единственные допустимые источники для ответа.\n\n"
        f"{context}\n\n"
        f"Вопрос: {question}\n\n"
        "Сформируй ответ строго по источникам и укажи ссылки [SOURCE_N]."
    )
